import "dotenv/config";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { db } from "../src/db/connection.js";
import { isEtfSector } from "../src/lib/tickerCalendarRelevance.js";
import { buildVolatilityModelTables, type TickerHistoryInput } from "../src/lib/volatilityModelTablesBuilder.js";

// Rebuilds src/lib/volatilityModelTables.generated.ts (the valuation model's fat-tail and calibration tables) from the
// daily bars, IBKR's daily implied volatility and the earnings calendar of the database in DATABASE_URL. Reads only.
// Run it on a database with the full bar history (staging or a copy of it), review the diff, commit the file.

const maxHorizon = 35; // 45 calendar days ≈ 31 sessions, with room
const bucketCount = 500;

const tickerRows: { id: string; symbol: string; sector: string | null }[] = await db("tickers").select("id", "symbol", "sector");
const barRows = await db("daily_price_bars")
  .select("ticker_id", db.raw('trading_date::text as "tradingDate"'), "open_price", "high_price", "low_price", "close_price", "volume", "implied_volatility")
  .orderBy([{ column: "ticker_id" }, { column: "trading_date" }]);
const earningsRows: { ticker_id: string; eventDate: string }[] = await db("ticker_calendar_events").where({ event_type: "earnings" }).select("ticker_id", db.raw('event_date::text as "eventDate"'));

const tickers: TickerHistoryInput[] = tickerRows.map((ticker) => ({
  symbol: ticker.symbol,
  group: isEtfSector(ticker.sector) ? "etf" : "stock",
  bars: barRows
    .filter((row) => row.ticker_id === ticker.id && row.open_price !== null && row.close_price !== null)
    .map((row) => ({ tradingDate: row.tradingDate, open: Number(row.open_price), high: Number(row.high_price), low: Number(row.low_price), close: Number(row.close_price), volume: Number(row.volume ?? 0), impliedVolatility: row.implied_volatility === null ? null : Number(row.implied_volatility) })),
  earningsDatesIso: earningsRows.filter((row) => row.ticker_id === ticker.id).map((row) => row.eventDate),
}));
const usable = tickers.filter((ticker) => ticker.bars.length > 22);
console.log(`tickers: ${usable.length} (${usable.filter((t) => t.group === "etf").map((t) => t.symbol).join(", ")} as ETFs)`);

const tables = buildVolatilityModelTables(usable, { maxHorizon, bucketCount, builtAtIso: new Date().toISOString(), source: `daily_price_bars of ${usable.length} tickers (${usable.map((t) => t.symbol).join(", ")})` });
console.log(`sample ${tables.sampleFromIso} → ${tables.sampleToIso}; windows per horizon (stock h=1/5/21/35): ${[1, 5, 21, 35].map((h) => tables.sampleCounts.stock[h - 1]).join("/")}; ETF h=1/5/21/35: ${[1, 5, 21, 35].map((h) => tables.sampleCounts.etf[h - 1]).join("/")}`);
for (const row of tables.calibration) console.log(`calibration h=${row.horizon}: ${row.points.map((point) => `${(point.predictedMargin * 100).toFixed(0)}%→${(point.realizedMargin * 100).toFixed(1)}% [raw ${(point.rawRealizedMargin * 100).toFixed(1)}%, ${(point.realizedLow * 100).toFixed(1)}..${(point.realizedHigh * 100).toFixed(1)}] (${point.count})`).join(", ")}`);

const target = fileURLToPath(new URL("../src/lib/volatilityModelTables.generated.ts", import.meta.url));
writeFileSync(
  target,
  `// Generated by \`npm run model:build-tables\` (scripts/build-volatility-model-tables.ts) — do not edit by hand.\n` +
    `import type { VolatilityModelTables } from "./volatilityModelTables.js";\n\n` +
    `export const volatilityModelTables: VolatilityModelTables = ${JSON.stringify(tables)};\n`,
);
console.log(`wrote ${target}`);
await db.destroy();
